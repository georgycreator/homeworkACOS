// log.h — логирование через дескрипторы файлов.
//
// Штатный вывод (события, статистика, карты) идёт через системный
// вызов write(), без буферизации stdio.
//
// Аварийные сообщения до открытия лога (например, об ошибке конфигурации
// или обработчиков сигналов) пишутся напрямую в stderr через fprintf
// в main.c — это допустимо, потому что лог-файл ещё не открыт.
#ifndef LOG_H
#define LOG_H

// Открыть лог-файл. Возвращает 0 при успехе, -1 при ошибке.
int  log_open(const char *path);

// Закрыть лог-файл.
void log_close(void);

// Записать строку и в консоль (fd 1), и в лог-файл.
int  log_printf(const char *fmt, ...);

// Записать строку только в консоль (fd 1), не в лог.
int  log_console(const char *fmt, ...);

#endif // LOG_H
