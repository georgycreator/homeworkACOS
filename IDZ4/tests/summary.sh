#!/usr/bin/env bash
# summary.sh ФАЙЛ — выделяет из вывода моделирования (IDZ3 или IDZ4) итоговые показатели
# в нормализованном виде, пригодном для точного сравнения: выстрелы, попадания, промахи,
# уничтоженные цели, остатки и расход боезапаса, потери, вердикт и число тактов.
grep -E "Выстрелов всего|Попаданий|Уничтожено целей противника|Всего израсходовано|Своих целей: живых|Потеряно своих|Тяжёлых снарядов осталось|Обычных снарядов осталось|^Потери:|^Победа|^Преимущество|^Ничья|^\[MAIN\].*Тактов:" "$1" \
  | sed -E 's/[[:space:]]+/ /g; s/^\[MAIN\].*Тактов: ([0-9]+).*/ТАКТОВ \1/'
