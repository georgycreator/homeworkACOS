// proto.h — прикладной протокол «мортирной дуэли» поверх TCP.
//
// Транспорт — поток байт, поэтому сообщения оформлены как текстовые строки,
// заканчивающиеся '\n' (длина не более PROTO_MAX_LINE). Первое слово строки —
// команда, остальное — её аргументы, разделённые пробелами.
//
// Клиент -> сервер:
//   HELLO <роль>                          представление (первое сообщение)
//   ACK <такт>                            государство обработало такт
//   RESUPPLY <такт> <кол-во>              запрос пополнения запаса (государство)
//   SHOT <такт> <R|H> <стр> <стлб> <бросок> <rng> <сектор>
//                                         выстрел; rng и сектор — состояние ГПСЧ и обхода
//                                         ПОСЛЕ этого выстрела (сервер хранит их для точного
//                                         возобновления подразделения после переподключения)
//   PONG                                  ответ на PING (проверка «живости» клиента)
//   PASS <такт>                           подразделение не стреляет в этом такте
//   BYE                                   штатное отключение
// Сервер -> клиент:
//   WELCOME <роль> <версия>               начало описания сессии
//   CFG <ключ> <значение...>              параметры сессии
//   STATE <ключ> <число>                  текущее состояние (для переподключения)
//   MAP <A|B> <строка> <символы>          карта территории (T цель, x разрушена, . пусто)
//   TGT <A|B> <стр> <стлб> <цена> <тип>   цель (только для первой сотни)
//   WELCOME_END <фаза> <такт>             конец описания сессии
//   TICK <такт>                           начало такта (государствам)
//   GUNTICK <такт> <reg> <area> <due> <обычных> <тяжёлых> <расход> <выстрелов>
//   RESULT <такт> <ok|код> ...            итог выстрела (стрелку)
//   DTGT <стр> <стлб> <цена> <тип>        потерянная цель (пострадавшему государству)
//   IMPACT <такт> <R|H> <стр> <стлб> <исход> <число> <цена> <живых> <стоим.> <потери>
//   SUPPLY <такт> <кол-во> <обычных>      пополнение выполнено
//   CEASEFIRE <причина...>                сторона прекращает огонь
//   TXT <текст>                           справочное сообщение участникам
//   EVT <текст>                           строка общего журнала (наблюдателям)
//   SUMMARY <текст>                       итог для участника
//   PAUSE/RESUME <текст>                  приостановка и возобновление
//   END <код причины> <тактов>            завершение моделирования
//   PING                                  проверка «живости» (клиент обязан ответить PONG)
//   ERR <текст>                           ошибка (затем сервер закрывает соединение)
#ifndef PROTO_H
#define PROTO_H

#define PROTO_VERSION   1
#define PROTO_MAX_LINE  4096     // максимальная длина строки протокола
#define PROTO_MAX_TGT   200      // сколько целей передаётся списком

// Роли участников. Первые четыре — обязательные участники модели,
// наблюдатели подключаются в любом количестве и в любой момент.
typedef enum {
    ROLE_NONE     = -1,
    ROLE_SIDE_A   = 0,   // государство A (территория, потери, пополнение)
    ROLE_SIDE_B   = 1,   // государство B
    ROLE_GUN_A    = 2,   // огневое подразделение A
    ROLE_GUN_B    = 3,   // огневое подразделение B
    ROLE_OBSERVER = 4    // наблюдатель
} role_t;

#define ROLE_PARTICIPANTS 4

const char *role_name(int role);           // "side-A", ..., "observer"
int         role_parse(const char *name);  // ROLE_NONE при ошибке

static inline int role_is_side(int r) { return r == ROLE_SIDE_A || r == ROLE_SIDE_B; }
static inline int role_is_gun(int r)  { return r == ROLE_GUN_A  || r == ROLE_GUN_B; }
// Индекс стороны (0 — A, 1 — B) для государства и для огневого подразделения.
static inline int role_side_index(int r) { return role_is_gun(r) ? r - ROLE_GUN_A : r - ROLE_SIDE_A; }

// Причины завершения моделирования.
typedef enum {
    STOP_NATURAL = 0,   // обе стороны прекратили огонь
    STOP_LIMIT   = 1,   // достигнут лимит тактов
    STOP_SIGNAL  = 2,   // прерывание оператором сервера
    STOP_ERROR   = 3,   // внутренняя ошибка
    STOP_ABSENT  = 4    // участник не вернулся за отведённое время
} stop_reason_t;

const char *stop_reason_text(int code);

// Исходы выстрела (передаются словом).
typedef enum {
    OUT_MISS_ACCURACY = 0,  // не попал из-за точности
    OUT_MISS_DESTROYED,     // клетка уже разрушена
    OUT_MISS_EMPTY,         // пустая клетка
    OUT_HIT,                // цель уничтожена
    OUT_AREA_NONE,          // тяжёлый залп никого не задел
    OUT_AREA_HIT            // тяжёлый залп уничтожил цели
} outcome_t;

const char *outcome_token(int o);          // "miss-accuracy", "hit", ...
int         outcome_parse(const char *s);  // -1 при ошибке

// Причины отказа в выстреле.
typedef enum {
    REJ_NONE = 0,
    REJ_LATE,        // такт уже завершён / фаза не та
    REJ_DUP,         // второй выстрел за такт
    REJ_CEASEFIRE,   // сторона уже прекратила огонь
    REJ_NOAMMO,      // нет снарядов нужного типа
    REJ_BUDGET,      // не хватает бюджета
    REJ_BADARGS,     // неверные аргументы
    REJ_BADCOORD,    // координаты вне территории противника
    REJ_BADSTATE,    // выстрел вне фазы стрельбы
    REJ_NOTDUE       // тяжёлый залп раньше срока по расписанию area_every
} reject_t;

const char *reject_token(int r);
const char *reject_text(int r);            // по-русски, для вывода
int         reject_parse(const char *s);

#endif // PROTO_H
